import { test, expect } from '@playwright/test';
import { preparePage, goTo } from './static-helpers.js';

test('forecast evidence explains inputs and opens corrections without saving',async({page},testInfo)=>{
  await preparePage(page);
  await page.goto('/');
  await page.getByRole('button',{name:/guest/i}).click();
  await page.getByRole('button',{name:'Load example budget'}).click();
  await expect(page.getByRole('heading',{name:'Overview'})).toBeVisible();
  await page.getByRole('button',{name:'Expand Accounts',exact:true}).click();
  await goTo(page,'net-worth');
  const panel=page.locator('section.forecast-readiness');
  const snapshot=()=>page.evaluate(async()=>{
    const {state,session}=await import('/js/app.js');
    return {displayedForecasts:[...document.querySelectorAll('.bv-chart-change')].map(el=>el.textContent),accounts:structuredClone(state.accounts),transactions:structuredClone(state.transactions),forecast:session.query('forecast.simulation',{date:'2026-09-15'}).value};
  });
  await expect(page.locator('.bv-chart-change')).toHaveCount(2);
  await expect(page.locator('.bv-chart-change').first()).toContainText('Change:');
  const before=await snapshot();
  expect(before.accounts.some(a=>a.id==='acct-checking')).toBe(true);
  const accounts=panel.locator('[data-readiness-detail="accounts"]');
  const assumptions=panel.locator('[data-readiness-detail="assumptions"]');
  await expect(panel.getByRole('heading',{name:'Things to check'})).toBeVisible();
  await expect(accounts).not.toHaveAttribute('open','');
  await expect(assumptions).not.toHaveAttribute('open','');
  await expect(panel.getByText('Missing transactions and future payments may still affect the forecast.')).toBeVisible();
  await accounts.locator('summary').first().focus();await page.keyboard.press('Enter');
  const checking=panel.locator('[data-readiness-detail="account:acct-checking"]');
  await checking.locator('summary').click();
  await expect(checking.getByText(/does not prove/)).toBeVisible();
  await expect(checking.getByText(/Latest recorded transaction: 20/)).toBeVisible();
  await panel.locator('.forecast-readiness-issues [data-readiness-action="reconcile"][data-readiness-id="acct-checking"]').click();
  const sheet=page.locator('[data-sheet-open]').last();
  await expect(sheet).toBeVisible();
  await sheet.getByRole('button',{name:'Cancel',exact:true}).click();
  await expect(page.locator('.sheet-overlay')).toHaveCount(0);
  await expect(accounts).not.toHaveAttribute('open','');
  await expect.poll(snapshot).toEqual(before);
  await page.setViewportSize({width:1440,height:1100});
  await page.evaluate(()=>document.documentElement.dataset.theme='light');
  await expect(page.locator('.toast')).toHaveCount(0);
  await panel.getByRole('heading',{name:'Things to check'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:testInfo.outputPath('forecast-inputs-desktop-light.png'),animations:'disabled'});
  const bank=before.accounts.find(a=>a.id==='acct-checking');
  const growth=page.getByRole('textbox',{name:`Expected yearly growth for ${bank.name}, in percent`});
  await growth.fill('3');await growth.blur();
  await expect(panel.getByText('This view includes unsaved simulation assumptions.')).toBeVisible();
  await expect(assumptions).not.toHaveAttribute('open','');
  expect((await snapshot()).accounts).toEqual(before.accounts);
  expect((await snapshot()).transactions).toEqual(before.transactions);
  await page.setViewportSize({width:390,height:844});
  await page.evaluate(()=>document.documentElement.dataset.theme='dark');
  await panel.getByRole('heading',{name:'Things to check'}).scrollIntoViewIfNeeded();
  await page.screenshot({path:testInfo.outputPath('forecast-inputs-narrow-dark.png'),animations:'disabled'});
  expect(await panel.evaluate(e=>e.scrollWidth<=e.clientWidth+1)).toBe(true);
  expect(page.__errors).toEqual([]);
});
