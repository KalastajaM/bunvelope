// Every locale but EN is lazy-loaded: an English user never fetches or parses
// the Finnish or Dutch dictionary (~1.4k keys each). While a dictionary is
// null, t() falls through to the EN fallback below — boot awaits loadLocale()
// so users never see that state.
export const LOCALES = ['fi', 'en', 'nl'];

// Locale label as written in that language, for the language picker.
export const LOCALE_NAMES = { fi: 'Suomi', en: 'English', nl: 'Nederlands' };

// BCP 47 tag per app language, for Intl date/number formatting.
const BCP47 = { fi: 'fi-FI', en: 'en-US', nl: 'nl-NL' };

const DICTS = { fi: null, en: EN, nl: null };

const LOADERS = {
  fi: () => import('./i18n/fi.js'),
  nl: () => import('./i18n/nl.js'),
};

export async function loadLocale(l) {
  if (LOADERS[l] && !DICTS[l]) {
    DICTS[l] = (await LOADERS[l]()).default;
  }
}

export function isLocaleLoaded(l) {
  return !LOADERS[l] || !!DICTS[l];
}

// Exported for parity tests only — do not import in app code; use t() instead.
export const _DICTS_FOR_TEST = DICTS;
let lang = 'fi';

export function getLang() { return lang; }

/** BCP 47 tag for the active language — use for Intl.* / toLocaleDateString. */
export function langLocale() { return BCP47[lang] ?? BCP47.en; }

export function setLang(l) {
  lang = LOCALES.includes(l) ? l : 'fi';
  // Finnish writes the currency symbol after the amount ("8 531,97 €").
  setCurrencyAfterAmount(lang === 'fi');
  // Keep the document language in sync so assistive tech uses the right
  // pronunciation rules. Guarded for non-DOM (test) environments.
  if (typeof document !== 'undefined' && document.documentElement) {
    document.documentElement.lang = lang;
  }
}

export function t(path) {
  const parts = path.split('.');
  let cur = DICTS[lang];
  for (const p of parts) { cur = cur?.[p]; if (cur == null) break; }
  if (cur == null) {
    cur = DICTS.en;
    for (const p of parts) { cur = cur?.[p]; if (cur == null) break; }
  }
  if (typeof cur === 'string' && cur.includes('{cur}')) {
    return cur.replaceAll('{cur}', getCurrencySymbol());
  }
  return cur ?? path;
}

export function trCat(cat) {
  const v = t('cat.' + cat);
  return v !== ('cat.' + cat) ? v : cat;
}

export function trEnv(envelope) {
  if (!envelope) return '';
  const key = envelope.i18n_key || envelope.name;
  const translated = t('env.names.' + key);
  if (translated !== ('env.names.' + key)) return translated;
  return envelope.name ?? '';
}

// A bare 'YYYY-MM-DD' is a calendar date, but `new Date()` reads it as UTC
// midnight, which is the previous day anywhere west of UTC. Build it from
// its parts instead; full timestamps still go through `new Date()`.
function toLocalDate(iso) {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(String(iso));
  return m ? new Date(Number(m[1]), Number(m[2]) - 1, Number(m[3])) : new Date(iso);
}

export function fmtDateLang(iso) {
  if (!iso) return '';
  const d = toLocalDate(iso);
  if (Number.isNaN(d.getTime())) return String(iso);
  // Finnish and Dutch both write d.m.yyyy / d-m-yyyy rather than a month name.
  if (lang === 'fi') return `${d.getDate()}.${d.getMonth()+1}.${d.getFullYear()}`;
  if (lang === 'nl') return `${d.getDate()}-${d.getMonth()+1}-${d.getFullYear()}`;
  return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric' });
}

const SHORT_MONTHS = {
  fi: ['tammi','helmi','maalis','huhti','touko','kesä','heinä','elo','syys','loka','marras','joulu'],
  nl: ['jan','feb','mrt','apr','mei','jun','jul','aug','sep','okt','nov','dec'],
};

export function fmtDateShortLang(iso) {
  if (!iso) return '';
  const d = toLocalDate(iso);
  if (Number.isNaN(d.getTime())) return String(iso);
  const months = SHORT_MONTHS[lang];
  // Finnish writes an ordinal dot after the day ("5. tammi"); Dutch does not.
  if (months) return `${d.getDate()}${lang === 'fi' ? '.' : ''} ${months[d.getMonth()]}`;
  return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric' });
}

/** 'YYYY-MM' → "Jan 2026" / "tammi 2026" / "jan 2026"; anything else passes through. */
export function fmtMonthLang(ym) {
  const m = /^(\d{4})-(\d{2})$/.exec(String(ym ?? ''));
  if (!m) return ym ?? '';
  const year = Number(m[1]);
  const month = Number(m[2]) - 1;
  const months = SHORT_MONTHS[lang];
  if (months) return `${months[month]} ${year}`;
  return new Date(year, month, 1).toLocaleDateString('en-US', { month: 'short', year: 'numeric' });
}
